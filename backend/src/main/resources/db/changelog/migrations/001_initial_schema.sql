--changeset cbiallo:016-create-notifications
CREATE TABLE notifications (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_profile_id BIGINT NOT NULL,
    sender_profile_id    BIGINT,
    type                 TEXT   NOT NULL CHECK (type IN (
                             'like_post','like_comment','like_story',
                             'comment','comment_reply',
                             'follow','follow_request','follow_accepted',
                             'mention_post','mention_comment','mention_story',
                             'tag','message','story_view'
                         )),
    reference_type       TEXT   CHECK (reference_type IS NULL OR reference_type IN ('post','comment','story','chat','profile')),
    reference_id         BIGINT,
    is_read              BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_profile_id) REFERENCES profiles(id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_sender    FOREIGN KEY (sender_profile_id)    REFERENCES profiles(id) ON DELETE SET NULL
);

CREATE INDEX idx_notifications_recipient ON notifications(recipient_profile_id, created_at DESC);
CREATE INDEX idx_notifications_unread    ON notifications(recipient_profile_id, is_read) WHERE is_read = FALSE;
--rollback DROP TABLE notifications;
