-- 3. FOLLOWS
-- ============================================================

--changeset cbiallo:004-create-follows
CREATE TABLE follows (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_profile_id  BIGINT NOT NULL,
    following_profile_id BIGINT NOT NULL,
    status               TEXT   NOT NULL DEFAULT 'accepted'
                                CHECK (status IN ('pending','accepted','rejected')),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at           TIMESTAMPTZ, -- soft delete

    CONSTRAINT chk_follows_no_self CHECK (follower_profile_id != following_profile_id),
    CONSTRAINT fk_follows_follower  FOREIGN KEY (follower_profile_id)  REFERENCES profiles(id) ON DELETE CASCADE,
    CONSTRAINT fk_follows_following FOREIGN KEY (following_profile_id) REFERENCES profiles(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX idx_follows_unique_active ON follows(follower_profile_id, following_profile_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_follows_follower  ON follows(follower_profile_id)  WHERE deleted_at IS NULL AND status = 'accepted';
CREATE INDEX idx_follows_following ON follows(following_profile_id) WHERE deleted_at IS NULL AND status = 'accepted';
CREATE INDEX idx_follows_pending   ON follows(following_profile_id) WHERE deleted_at IS NULL AND status = 'pending';
CREATE INDEX idx_follows_rejected  ON follows(following_profile_id) WHERE deleted_at IS NULL AND status = 'rejected';
--rollback DROP TABLE follows;

