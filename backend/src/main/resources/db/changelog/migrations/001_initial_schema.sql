-- 2. PROFILES
-- ============================================================

--changeset cbiallo:003-create-profiles
CREATE TABLE profiles (
    id                BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT  NOT NULL UNIQUE,
    username          CITEXT  NOT NULL UNIQUE,
    full_name         VARCHAR(64),
    profile_image_url TEXT,
    bio               VARCHAR(150),
    website_url       TEXT,
    gender            TEXT    CHECK (gender IS NULL OR gender IN ('male','female','prefer_not_to_say','custom')),
    custom_gender     TEXT,
    is_private        BOOLEAN NOT NULL DEFAULT FALSE,
    is_verified       BOOLEAN NOT NULL DEFAULT FALSE,
    followers_count   INTEGER NOT NULL DEFAULT 0,
    following_count   INTEGER NOT NULL DEFAULT 0,
    posts_count       INTEGER NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at        TIMESTAMPTZ, -- soft delete

    CONSTRAINT chk_profiles_gender CHECK (
        (gender = 'custom' AND custom_gender IS NOT NULL)
        OR (gender IS DISTINCT FROM 'custom' AND custom_gender IS NULL)
    ),
    CONSTRAINT fk_profiles_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_profiles_username ON profiles(username) WHERE deleted_at IS NULL;
CREATE INDEX idx_profiles_user_id  ON profiles(user_id)  WHERE deleted_at IS NULL;
--rollback DROP TABLE profiles;

