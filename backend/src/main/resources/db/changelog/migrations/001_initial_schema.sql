--changeset cbiallo:002-create-users
CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number      VARCHAR(15)  UNIQUE,
    email             VARCHAR(255) UNIQUE,
    password_hash     VARCHAR(512) NOT NULL,
    date_of_birth     DATE         NOT NULL,
    is_email_verified BOOLEAN      NOT NULL DEFAULT FALSE,
    is_phone_verified BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at     TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    deleted_at        TIMESTAMPTZ, -- soft delete

    CONSTRAINT chk_users_contact CHECK (phone_number IS NOT NULL OR email IS NOT NULL)
);

CREATE INDEX idx_users_email ON users(email)        WHERE email        IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX idx_users_phone ON users(phone_number) WHERE phone_number IS NOT NULL AND deleted_at IS NULL;
--rollback DROP TABLE users;

